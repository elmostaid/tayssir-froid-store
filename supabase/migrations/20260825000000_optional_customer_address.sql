-- العنوان الكامل يصير اختيارياً في طلبات الموقع.
--
-- السبب تجاري لا تقني: أغلب زبائن قطع الغيار يطلبون من محلّ معروف في مدينة
-- معروفة، ويُتَّفق على مكان التسليم في مكالمة التأكيد. فرضُ العنوان كان
-- يوقف الطلب عند آخر حقل قبل واتساب — أي في أسوأ نقطة ممكنة.
--
-- الاسم والهاتف والمدينة تبقى إجبارية: بدونها لا يمكن تأكيد الطلب أصلاً.
--
-- قيد الطول (‎<= 300) يبقى كما هو ولا يحتاج تعديلاً: شرط CHECK على قيمة
-- NULL يُقيَّم إلى unknown، وPostgres يقبل الصفّ — فالعنوان الفارغ يمرّ
-- والعنوان الطويل يبقى مرفوضاً.
alter table public.orders
  alter column customer_address drop not null;

comment on column public.orders.customer_address is
  'العنوان الكامل — اختياري. NULL يعني أن الزبون لم يُدخل عنواناً، ويُعرض «غير محدد» في اللوحة والوصل.';
