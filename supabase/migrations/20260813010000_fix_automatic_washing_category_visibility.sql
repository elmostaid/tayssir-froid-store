-- إصلاح: تصنيف "قطع غيار آلات غسيل الملابس الأوتوماتيكية"
-- (automatic-washing-machine-parts) كان is_active = false، فكان هذا وحده
-- يُخفيه بالكامل عن الموقع العام (الرئيسية، الهيدر، صفحة التصنيف، وحتى
-- صفحات منتجاته الـ28 نفسها) رغم أن منتجاته منشورة فعلاً — كل من
-- catalog_categories وcatalog_products (انظر 20260730000002_security.sql)
-- تشترط is_active = true على التصنيف، بينما لوحة الإدارة تستعلم الجداول
-- الأصلية مباشرة فتبقى تُظهر المنتجات بلا أي علاقة بهذا العطل، ما يفسّر
-- ظهورها "منشورة" فالإدارة واختفاءها فالموقع. الإصلاح هنا لا يُنشئ أي
-- تصنيف ولا يُعدّل أي منتج ولا يمسّ أي تصنيف آخر — فقط يُعيد تفعيل هذا
-- التصنيف بعينه، ومطابق بـ slug (وليس id) للمحمولية بين البيئات. الشرط
-- is_active = false يجعل إعادة تشغيل هذا الملف بلا أي أثر إن كان مفعَّلاً
-- أصلاً.
update public.categories
set is_active = true
where slug = 'automatic-washing-machine-parts'
  and is_active = false;
