-- إصلاح: صور منتجات مكسورة على بعض هواتف iPhone تحديداً (تعمل على أجهزة
-- أخرى بنفس الصفحة). التشخيص: كل صور دفعة "product-images-v3" (المستوردة
-- حديثاً، تغطي قطع غيار آلات الغسيل/الثلاجات/المكيفات المُبلَّغ عنها)
-- محفوظة كـPNG بامتداد RGBA وباسم ملف عربي يحوي مسافات (مثال:
-- "TF-WM-040__موطور نشاف LG رأس غليظ.png"، مُرمَّز كـpercent-encoding داخل
-- storage_path نفسه). هذا النمط غير متسق مع بقية صور الموقع (JPEG baseline
-- بامتداد ASCII بسيط)، وهو نفس فئة العطل المُصلَحة سابقاً لصور التصنيفات
-- (WebP بحاوية VP8X+ICC) في 3099b0b/e8ab764: تنسيق/تسمية غير موحّدة تسبب
-- فشل عرض متقطع على بعض المتصفحات المحمولة رغم صحة الملف بنيوياً. لم
-- يُعثر على عطل بنيوي واحد محدد داخل كل ملف (كل الصور فُحصت: PNG صالح،
-- بلا شفافية فعلية، أبعاد موحّدة)، لذا الإصلاح هنا يوحّد الدفعة كاملة إلى
-- نفس القالب الآمن المُعتمَد فالموقع: JPEG baseline (سطر الكود الذي حوّل
-- الملفات فعلياً على القرص موجود فنفس الالتزام على فرع الإصلاح)، واسم ملف
-- ASCII بسيط <SKU>.jpg بدل الاسم العربي الأصلي — يزيل في آن واحد خطر فك
-- ترميز قناة الشفافية (alpha) على متصفحات قديمة وخطر ترميز/فك مسار URL
-- يحوي حروفاً عربية ومسافات.
--
-- (public/product-images/ القديم — بما فيه منتجات TF-CK — مُستثنى عمداً:
-- هذا المجلد مُدرَج فـ.gitignore، أي أنه لا يُدار عبر git/هذا الفرع أصلاً،
-- فتوحيد صوره خارج نطاق هذا الإصلاح.)
--
-- هذا الجدول (product_images) هو المصدر الحقيقي الوحيد لمسار كل صورة —
-- لا يوجد عمود صورة مكرَّر في products. التحديث مطابق بالنمط (storage_path
-- LIKE) لا بقيمة كاملة ثابتة، فيبقى صحيحاً بغضّ النظر عن الاسم العربي
-- الأصلي الدقيق لكل صف. مضمون التكرار الآمن (idempotent): يستثني الصفوف
-- المطابقة أصلاً للقيمة الجديدة، فإعادة تشغيله بعد نجاحه أول مرة بلا أي أثر.
update public.product_images pi
set storage_path = 'product-images-v3/' || s.sku || '/' || s.sku || '.jpg'
from (
  select id, split_part(storage_path, '/', 2) as sku
  from public.product_images
  where storage_path like 'product-images-v3/%'
) s
where pi.id = s.id
  and pi.storage_path <> 'product-images-v3/' || s.sku || '/' || s.sku || '.jpg';
