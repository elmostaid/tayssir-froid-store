-- تسويات التوصيل، المرحلة 2: الطلبيات الراجعة كخسارة حقيقية من الفاتورة.
--
-- ## لماذا
--
-- الكرطونة الراجعة في فاتورة BigDelivery تحمل رسوماً (مثلاً 20 درهم) بتحصيل
-- صفر: الشركة تخصمها من صافي الفاتورة. هذه خسارة مدفوعة فعلاً، لكن النظام كان
-- يحجب الكرطونة فقط فلا تُسجَّل على أي طلبية ولا تظهر في أي مجموع.
--
-- ## ما يتغيّر
--
-- **عمود واحد جديد في جدول التسويات (جدول هذا النظام نفسه):** `outcome`.
--   delivered  الكرطونات تسلّمات والفلوس تحصّلات (كل التسويات السابقة).
--   returned   الكرطونات رجعات: نسجّل الرسوم المدفوعة كتكلفة توصيل حقيقية
--              للطلبية، ولا نغيّر حالتها — تغيير «راجعة» كيرجّع المخزون، فكيبقى
--              قرار المالك من صفحة الطلبية ملي توصلو السلعة.
--
-- لا شيء في `orders` ولا في أي جدول آخر. كل صفّ قائم يأخذ القيمة الافتراضية
-- `delivered`، وهي بالضبط معناه. لا حذف ولا تعديل لبيانات موجودة.
--
-- ## التراجع عن هذا الملف
--
--   alter table public.carrier_order_settlements drop column outcome;
--
-- (بعد التراجع عن أي تسوية «returned» من اللوحة أولاً، حتى لا تبقى تكلفة
-- توصيل مكتوبة بلا تسوية تشرحها.)

begin;

alter table public.carrier_order_settlements
  add column outcome text not null default 'delivered'
    check (outcome in ('delivered', 'returned'));

comment on column public.carrier_order_settlements.outcome is
  'delivered: تسلّمات وتحصّلات. returned: رجعات — رسومها خسارة مسجَّلة، والحالة ما تبدلاتش.';

commit;
