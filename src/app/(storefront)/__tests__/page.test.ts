import { describe, expect, test } from "vitest";
import { buildTrustPoints, MIN_QTY_NOTE } from "@/app/(storefront)/page";
import { DELIVERY_AVAILABILITY } from "@/lib/delivery";

describe("buildTrustPoints (نقاط الثقة الأربع فأعلى الصفحة الرئيسية)", () => {
  // النقاط ثابتة: سطر التوصيل لم يعد مشتقّاً من رقم الرسوم، لأن السياسة
  // نفسها لم تعد ثنائية (مجاني/بثمن) بل واحدة — توفّرٌ ومصاريف تُحدَّد
  // عند التأكيد.
  test("النقاط الأربع كما يراها الزائر", () => {
    expect(buildTrustPoints()).toEqual([
      "البيع بالقطعة والجملة حسب المنتوج",
      "أثمنة مناسبة للتجار والحرفيين",
      "الدفع عند الاستلام بعد معاينة السلعة",
      `🚚 ${DELIVERY_AVAILABILITY}`,
    ]);
  });

  /**
   * العطل الذي يحرسه: المتجر كان يقول «البيع بالجملة فقط»، وبياناته
   * تكذّبه — 240 منتجاً من 419 كميته الدنيا قطعة واحدة. فالزائر الذي
   * يحتاج قطعة كان يقرأ أنه ليس زبوناً لنا ويغادر. أي رجوع إلى «فقط»
   * يعيد ذلك الباب المغلق.
   */
  test("لا يُقصر المتجر على الجملة", () => {
    const text = buildTrustPoints().join(" ");
    expect(text).not.toMatch(/الجملة فقط|بالجملة فقط/);
    expect(text).toContain("بالقطعة والجملة");
  });

  // الوعد الذي أُلغي: لا يعود من أي باب.
  test("لا وعد بمجانية التوصيل ولا ذكر لثمنه", () => {
    const text = buildTrustPoints().join(" ");
    expect(text).not.toMatch(/مجان|بالمجان|free\s*shipping|gratuit/i);
    expect(text).not.toMatch(/\d[\d.,]*\s*(درهم|MAD)/i);
  });

  /**
   * شرح الكمية الدنيا عاد إلى الهيرو، لكن **خارج النقاط** لا ذيلاً على
   * إحداها: ذلك الذيل كان يُطيل النقطة حتى تلتفّ سطرين على الهاتف، وهو
   * سبب حذفه أصلاً. الشكل هو ما تغيّر، لا الحكم.
   */
  test("شرح الكمية الدنيا سطرٌ مستقلّ، لا ذيلٌ على نقطة", () => {
    const text = buildTrustPoints().join(" ");
    expect(text).not.toContain("الكمية الدنيا");
    expect(MIN_QTY_NOTE).toContain("الكمية الدنيا");
    expect(MIN_QTY_NOTE).toContain("حسب المنتوج");
  });

  // المعلومة صحيحة فقط إن كانت صفحة المنتج تعرضها فعلاً — وهي تعرضها
  // («الكمية الدنيا للطلب»). فالجملة توجّه الزائر إلى مكان موجود.
  test("سطر الكمية الدنيا يُحيل إلى صفحة المنتج", () => {
    expect(MIN_QTY_NOTE).toMatch(/صفحة كل منتوج/);
  });

  // أربع نقاط قصيرة: الهيرو يُقاس بما يُخفيه من المنتجات تحته.
  test("أربع نقاط فقط، وكل واحدة قصيرة تكفي سطراً واحداً", () => {
    const points = buildTrustPoints();
    expect(points).toHaveLength(4);
    for (const point of points) {
      expect(point.length).toBeLessThanOrEqual(40);
    }
  });

  // الحاجز أُلغي نهائياً، فأي مبلغ يظهر هنا كشرط شراء يكون كذباً على
  // الزبون ويعيد إليه بالضبط التردّد الذي ألغينا الحاجز لأجله.
  test("لا يذكر أي شرط مالي عام", () => {
    const text = buildTrustPoints().join(" ");
    expect(text).not.toMatch(/الحد الأدنى للطلب|أقل طلب|أقل قيمة/);
  });

  // «بلا حد أدنى» وعدٌ مطلق تكذّبه الكمية الدنيا لكل منتج.
  test("لا يعد الزبون بحرية مطلقة في الكمية", () => {
    expect(buildTrustPoints().join(" ")).not.toMatch(/بلا حد أدنى|أي كمية/);
  });

  /**
   * «بعد معاينة السلعة» وعدٌ عن طريقة التسليم الفعلية، لا يملك الموقع
   * بياناً يُثبته. أكّده صاحب المتجر صراحةً: شركات التوصيل تسمح للزبون
   * بمعاينة القطعة قبل الأداء. فهو يبقى — ويبقى مطابقاً لما تقوله بقية
   * الصفحات (صفحة المنتج، إتمام الطلب، صفحة الطلب، رسالة واتساب)،
   * بنفس الصياغة حرفياً حتى لا ينحرف أحدها عن الآخر.
   */
  test("وعد المعاينة قبل الأداء حاضر بنفس صياغة بقية الصفحات", () => {
    expect(buildTrustPoints()).toContain("الدفع عند الاستلام بعد معاينة السلعة");
  });
});
