/**
 * ما الذي يراه الزبون فعلاً — تعريف واحد لا يُكرَّر.
 *
 * **هذا الملف وُلد من عطل حقيقي.** كان ترتيب المنتجات اليدوي يُحسَب على كل
 * منتجات التصنيف (بما فيها المسودّات)، بينما صفحة التصنيف تقرأ من العرض
 * `catalog_products` الذي يستبعدها. النتيجة أن المسودّة كانت **تحجز مرتبة
 * لا تظهر**: في تصنيف المكيفات، مسودّة على المرتبة 2 جعلت كل منتج بعدها
 * يظهر قبل رقمه بمركز — يكتب المدير «3» فيجد المنتج ثانياً، ويكتب «9»
 * فيجده ثامناً. الرقم كان يُحفَظ صحيحاً، والاستعلام يرتّب صحيحاً، والخلل
 * كله في أن الطرفين كانا يعنيان بـ«المنتجات» شيئين مختلفين.
 *
 * فالقاعدة الآن: أي كود يحسب مرتبة أو موضعاً يجب أن يستعمل هذه القائمة
 * بعينها، لا قائمة يكتبها لنفسه. واختبار في
 * `catalog/__tests__/visibilityMatchesView.test.ts` يقرأ تعريف العرض من
 * القاعدة ويقارنه بهذا الثابت، فلا ينحرف أحدهما عن الآخر ثانيةً بصمت.
 */

/**
 * حالات المنتج التي تظهر في المتجر.
 *
 * `out_of_stock` معروض عمداً: المنتج يبقى في صفحته وفي تصنيفه بلا زرّ شراء
 * — إخفاؤه كان يعني رابطاً مكسوراً لكل من شارك القطعة أو حفظها.
 */
export const PUBLICLY_VISIBLE_STATUSES = ["published", "out_of_stock"] as const;

export type PubliclyVisibleStatus = (typeof PUBLICLY_VISIBLE_STATUSES)[number];

/** هل يظهر منتج بهذه الحالة للزبون؟ (التصنيف غير الفعّال يُخفيه أيضاً.) */
export function isPubliclyVisibleStatus(status: string): boolean {
  return (PUBLICLY_VISIBLE_STATUSES as readonly string[]).includes(status);
}
