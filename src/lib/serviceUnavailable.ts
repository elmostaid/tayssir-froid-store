/**
 * خطأ مخصَّص يعني: تعذّر الوصول لقاعدة البيانات، لا أن الصفحة غير موجودة.
 *
 * لماذا نرمي خطأً بدل عرض مكوّن ServiceUnavailable مباشرة (كما كان):
 * عرض المكوّن داخل الصفحة يجعل Next.js يُرسل **HTTP 200** مع صفحة العطل.
 * أثناء عطل 16 غشت بقي المتجر كله معطّلاً سبع دقائق وكل طلب يُسجَّل كنجاح —
 * فلا مراقبة خارجية ترى شيئاً، ومحركات البحث قد تفهرس صفحة العطل كمحتوى
 * شرعي للصفحة. رمي الخطأ يجعل Next.js يُرسل رمز خطأ خادم حقيقي (5xx)
 * ويعرض error.tsx، فيصبح العطل مرئياً لأي فحص توفّر وغير قابل للفهرسة.
 *
 * ملاحظة تقنية مهمة (تحقّقنا منها في مصدر Next.js 16 نفسه): لا توجد أي
 * واجهة عامة لإرجاع 503 تحديداً من مكوّن صفحة. الآلية الوحيدة التي تسمح
 * بالتحكم في رمز الحالة من الصفحات (HTTPAccessErrorStatus في
 * next/dist/client/components/http-access-fallback) تقبل 401 و403 و404
 * فقط. لذلك المسارات التي هي Route Handlers (الخلاصات وواجهات API) تُرجع
 * 503 صراحةً عبر Response، بينما الصفحات تُرجع 500 عبر هذا الخطأ — وكلاهما
 * 5xx يحقّق الغرض: عطل مرئي للمراقبة وغير مفهرس.
 */
export class ServiceUnavailableError extends Error {
  readonly isServiceUnavailable = true;

  constructor(context: string) {
    super(`الخدمة غير متوفرة مؤقتاً: تعذّر الوصول لقاعدة البيانات (${context})`);
    this.name = "ServiceUnavailableError";
  }
}

/** رؤوس قياسية لأي Route Handler يُرجع 503 فعلياً. */
export const SERVICE_UNAVAILABLE_HEADERS = {
  // يخبر العملاء ومحركات البحث أن العطل مؤقّت وأن عليهم إعادة المحاولة.
  "Retry-After": "60",
  // لا تُخزَّن صفحة العطل في أي ذاكرة وسيطة، وإلا بقيت تُقدَّم بعد التعافي.
  "Cache-Control": "no-store, must-revalidate",
  // لا تُفهرس أبداً كمحتوى شرعي.
  "X-Robots-Tag": "noindex",
} as const;
