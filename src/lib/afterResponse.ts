import { after } from "next/server";

/**
 * تنفيذ عمل جانبي **بعد** إرسال الجواب، لا قبله.
 *
 * المشكلة التي يحلّها: الزبون ينتظر جواب `/api/orders` مهلة قصيرة (2.5
 * ثانية) ثم يمضي إلى واتساب. أي عمل قياس نُضيفه داخل المسار قبل الجواب
 * يُبطئه، فيزيد عدد الطلبات التي تفوت تلك المهلة — أي أن إصلاح القياس
 * يُفسد تجربة الزبون. و`after` من Next.js موجودة لهذا بالضبط: تضمن تنفيذ
 * العمل بعد اكتمال الجواب، وتُبقي الدالة حيّة حتى ينتهي (وهو ما لا يضمنه
 * `void promise` المجرّد على منصّة serverless).
 *
 * لماذا الغلاف بدل نداء `after` مباشرة: `createOrder` تُستدعى أيضاً من
 * عشرات اختبارات التكامل بلا أي سياق طلب، و`after` ترمي هناك. الغلاف يرجع
 * إلى تنفيذ عادي في تلك الحالة، فلا اختبار ينكسر ولا سلوك إنتاجي يتغيّر.
 *
 * لا يرمي أبداً: العمل الجانبي لا يجوز أن يُسقط ما استدعاه.
 */
export function runAfterResponse(work: () => Promise<unknown> | unknown): void {
  const run = () => {
    try {
      void Promise.resolve(work()).catch((error) => {
        console.error("runAfterResponse: فشل عمل ما بعد الجواب", error);
      });
    } catch (error) {
      console.error("runAfterResponse: فشل عمل ما بعد الجواب", error);
    }
  };

  try {
    after(run);
  } catch {
    // خارج سياق طلب (اختبارات، أو نداء مباشر): نُنفّذ بلا حجز.
    run();
  }
}
