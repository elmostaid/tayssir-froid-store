import { revalidateTag, updateTag } from "next/cache";

/**
 * وسم واحد لكل ما يقرأه الزبون من الكتالوج (تصنيفات، منتجات، صور، متغيّرات،
 * إعدادات المتجر). كل هذه البيانات تتغيّر معاً من نفس المكان تقريباً (لوحة
 * الإدارة)، وحجمها كله أقل من ميغابايتين، فلا فائدة من تقسيمها إلى أوسمة
 * دقيقة: وسم واحد يعني أن أي تعديل من الإدارة يُظهر النتيجة فوراً على كل
 * صفحة، بلا أي احتمال أن ننسى إبطال وسم فرعي فيرى الزبون بيانات قديمة.
 */
export const CATALOG_TAG = "catalog";

/**
 * مدة صلاحية احتياطية فقط. المسار الطبيعي للتحديث هو الإبطال الصريح عبر
 * revalidateCatalog() عند كل تعديل من الإدارة وعند كل طلب جديد (لأنه يُنقص
 * المخزون). هذه المهلة شبكة أمان لأي مسار تعديل قد يُضاف مستقبلاً وينسى
 * استدعاء الإبطال — دقيقة واحدة قصيرة بما يكفي ألا يلاحظ الزبون شيئاً،
 * وطويلة بما يكفي لتمتصّ أي موجة زيارات مفاجئة بلا استعلام واحد إضافي.
 */
export const CATALOG_REVALIDATE_SECONDS = 60;

/**
 * تُستدعى بعد أي تعديل يمسّ ما يراه الزبون. مُجمَّعة هنا في دالة واحدة بدل
 * تكرار اسم الوسم في كل ملف إجراءات.
 *
 * نستعمل updateTag وليس revalidateTag عمداً. الفرق حاسم هنا:
 *   - revalidateTag(tag, "max") يُعلِّم البيانات «قديمة» ويُطبِّق
 *     stale-while-revalidate — أي أنّ المدير بعد حفظ ثمن جديد قد يرى الثمن
 *     القديم مرّة أخرى بينما يُجلَب الجديد في الخلفية. سلوك غير مقبول للوحة
 *     إدارة: يبدو وكأنّ الحفظ فشل.
 *   - updateTag يُبطل الذاكرة فوراً، فأول طلب بعده ينتظر البيانات الطازجة
 *     (وهو سلوك read-your-own-writes الذي يوثّقه Next.js لهذه الحالة
 *     بالضبط).
 * ملاحظة: updateTag لا يعمل إلا داخل Server Actions ويرمي خارجها. صار
 * لإنشاء الطلب مستدعٍ ثانٍ ليس Server Action — مسار /api/orders الذي
 * يستعمله المتصفح بـkeepalive لينجو الحفظ من مغادرة الصفحة إلى واتساب.
 * هناك كان updateTag يرمي **بعد** أن يُنشأ الطلب فعلاً، فيرجع المسار 500
 * على طلب ناجح، فتظنّ الواجهة أن الحفظ فشل وترسل نسخة إنقاذ بلا داعٍ.
 *
 * لذلك: updateTag حيث يعمل (لوحة الإدارة، حيث read-your-own-writes مطلوب
 * فعلاً)، وrevalidateTag حيث لا يعمل. مسار الزبون لا يحتاج قراءة فورية
 * لكتابته — يكفيه أن يرى الزائر التالي المخزون محدَّثاً.
 * كما أنّ الصيغة أحادية الوسيط من revalidateTag صارت مهجورة في Next.js 16.
 */
export function revalidateCatalog(): void {
  try {
    updateTag(CATALOG_TAG);
  } catch {
    revalidateTag(CATALOG_TAG, "max");
  }
}

/**
 * unstable_cache يتطلّب سياق تشغيل Next.js (incrementalCache) ويرمي
 * "Invariant: incrementalCache missing in unstable_cache" خارجه. هذا يقع في
 * سياقين حقيقيين في هذا المشروع:
 *   - اختبارات Vitest (تستورد الاستعلامات مباشرة بلا خادم Next.js).
 *   - سكريبتات tsx في scripts/ (gen-audit-report، validate-meta-feed).
 * في الحالتين لا يوجد ما يُخزَّن أصلاً (عملية قصيرة العمر)، والتخزين المؤقّت
 * تحسين أداء لا شرط صحّة — فالسلوك الصحيح هو تنفيذ الاستعلام مباشرة، لا
 * إسقاط العملية بخطأ.
 *
 * نطابق على نصّ الثابتة (invariant) لأنّ Next.js لا يوفّر أي واجهة عامة
 * للسؤال "هل نحن داخل سياق طلب؟". النطاق ضيّق عمداً: أي خطأ آخر يُعاد رميه
 * كما هو، فلا نُخفي أخطاء قاعدة بيانات حقيقية خلف هذا المسار.
 */
export function isMissingCacheContext(error: unknown): boolean {
  return (
    error instanceof Error &&
    error.message.includes("incrementalCache") &&
    error.message.includes("unstable_cache")
  );
}
