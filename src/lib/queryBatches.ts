/**
 * حدّ التزامن على استعلامات الصفحة الواحدة — للمتجر والإدارة معاً.
 *
 * ## لماذا انتقل هذا من `admin/sectionData.ts` إلى هنا
 *
 * كُتب في سبتمبر لصفحات الإدارة وحدها، فحُصِّنت `/admin/analytics` و
 * `/admin/reports` ولوحة التحكّم — وبقيت واجهة المتجر كما هي. ثم جاءت
 * الحملة الإعلانية ووجّهت حركتها إلى `/` و`/water-heaters`، وهما وحدهما
 * الصفحتان اللتان ظهرتا في سجلّ `Task timed out after 300 seconds`
 * (32 حالة / 32 زائراً متمايزاً). فالمكان الصحيح لهذه الدالّة ليس مجلّد
 * الإدارة.
 *
 * ## ما يفعله هذا الحدّ فعلاً — وما لا يفعله
 *
 * **مقيس** على قاعدة اختبار محلية خلف وسيط TCP يَعُدّ الاتصالات، بمجموعة
 * استعلامات الصفحة الرئيسية الحقيقية (8 للصفحة + 3 للترويسة والفوتر = 11):
 *
 * | | `Promise.all` | `inBatches(3)` |
 * |---|---|---|
 * | زائر واحد | **5 اتصالات من 5** (المجمّع مُشبَع) · 43ms | **3 من 5** · 42ms |
 * | 3 زوّار | 5 من 5 · 97ms | 5 من 5 · 96ms |
 * | 6 زوّار | 5 من 5 · 152ms | 5 من 5 · 173ms |
 * | 12 زائراً | 5 من 5 · 202ms | 5 من 5 · 215ms |
 *
 * فالمكسب الحقيقي والوحيد: **زائر واحد لم يبقَ يحتكر المجمّع كلّه.**
 * كان طلبٌ واحد على `/` يأخذ الخمسة فيجد التخطيط (ترويسة/فوتر) وأي طلب
 * ثانٍ طابوراً؛ الآن يبقى سلوتان حرّان دائماً. والثمن المقيس صفر لزائر
 * واحد، و6–14% زمناً تحت ضغط ستة زوّار أو أكثر.
 *
 * **ولا يفعل هذا الحدّ شيئاً** في مواجهة الذروة تحت الضغط: `max: 5` سقف
 * صلب، فالذروة تبقى 5 في الحالتين — الفائض ينتظر في طابور postgres.js لا
 * على الشبكة. **ولا يُصلح** الاستعلام الذي لا ينتهي (انظر `db.ts`: مهلة
 * `statement_timeout` لا تُطبَّق عبر Supavisor على المنفذ 6543، وهو السبب
 * الجذري الحقيقي للـ300 ثانية). هذا الملف يُنقص الضغط، لا يحدّ الزمن.
 */

/** أقصى عدد استعلامات متوازية تُطلقها صفحة واحدة: 3 من 5 في المجمّع. */
export const MAX_CONCURRENT_QUERIES = 3;

type AnyTask = () => Promise<unknown>;

/**
 * يُنفِّذ المهام على دفعات لا تتجاوز `size` مهمة متوازية، ويحفظ ترتيب
 * النتائج وأنواعها كما لو كانت `Promise.all`.
 *
 * الترتيب مقصود: الدفعة الأولى تحمل ما تعرضه الصفحة أولاً، فيصل أهمّ ما
 * في الصفحة قبل تفاصيلها.
 */
export async function inBatches<const T extends readonly AnyTask[]>(
  tasks: T,
  size: number = MAX_CONCURRENT_QUERIES
): Promise<{ -readonly [K in keyof T]: Awaited<ReturnType<T[K]>> }> {
  const results: unknown[] = [];
  for (let i = 0; i < tasks.length; i += size) {
    const batch = tasks.slice(i, i + size) as readonly AnyTask[];
    results.push(...(await Promise.all(batch.map((task) => task()))));
  }
  return results as { -readonly [K in keyof T]: Awaited<ReturnType<T[K]>> };
}
