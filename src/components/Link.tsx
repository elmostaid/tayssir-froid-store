import NextLink from "next/link";
import type { ComponentProps } from "react";

/**
 * الرابط الوحيد المستعمل في الموقع: `next/link` نفسه، لكن **بلا جلب مسبق
 * تلقائي** ما لم يُطلب صراحةً.
 *
 * ## لماذا (مقيس، نونبر 2026)
 *
 * كل صفحات الموقع ديناميكية (`force-dynamic`)، فكل طلب `.rsc` يصل إلى
 * Vercel تنفيذاً كاملاً لدالة خادم. والجلب المسبق الافتراضي يُطلق طلبين لكل
 * رابط يدخل الشاشة، قبل أن يضغط الزائر أي شيء. القياس على نسخة الإنتاج:
 *
 *   - /water-heaters (صفحة الحملة): 22 طلب خادم لزيارة واحدة، منها 20 جلباً مسبقاً.
 *   - /washing-machines: 30، منها 28.
 *   - الرئيسية: 56، منها 55. صفحة تصنيف: 59، منها 58. صفحة منتج: 15، منها 13.
 *
 * أي أن ~95% من استهلاك الدوال كان جلباً مسبقاً لصفحات لا يفتحها الزائر.
 * هذا ما أوصل الحساب إلى 1.2 مليون استدعاء (سقف Hobby: مليون) مقابل
 * ~10,700 جلسة حقيقية في الشهر، ثم إيقاف الموقع في 13/11/2026.
 *
 * ## ما الذي يتغيّر للزبون
 *
 * لا شيء في الوظائف: الرابط يعمل كما هو، والتنقّل يبقى داخل التطبيق بلا
 * إعادة تحميل. الفرق الوحيد أن الصفحة التالية تُطلب عند الضغط لا قبله —
 * وهي أصلاً ديناميكية، فالخادم كان سيُستدعى عند الضغط في كل الأحوال.
 *
 * `prefetch` الصريح يبقى ممكناً لرابط بعينه إن ثبتت الحاجة إليه. استيراد
 * `next/link` مباشرةً ممنوع في ESLint حتى لا يعود الجلب الافتراضي من باب جانبي.
 */
export default function Link({ prefetch = false, ...props }: ComponentProps<typeof NextLink>) {
  return <NextLink prefetch={prefetch} {...props} />;
}
